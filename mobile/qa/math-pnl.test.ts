/**
 * Suite for computeMonthDrill (the Monthly P&L breakdown) plus the smaller
 * roll-ups that share its row-selection rules: computeRepeatByMonth,
 * computeCalendar, computePayouts — all in src/logic.ts.
 *
 * Run: bash qa/run-tests.sh
 *
 * Fixtures mirror real production rows (D1 `spira`, read-only). Every expected
 * value is derived by hand in the comment above it. Assertions named [BUG]
 * assert the CORRECT value and FAIL today — they are the proof of a finding.
 */
import {
  computeCash, computeMonthDrill, computeRepeatByMonth, computeCalendar,
  computePayouts, LogBlock,
} from '../src/logic';

let pass = 0, fail = 0;
const failures: string[] = [];
function eq(name: string, got: any, want: any) {
  const g = JSON.stringify(got), w = JSON.stringify(want);
  if (g === w) { pass++; }
  else { fail++; failures.push(`✗ ${name}\n    got:  ${g}\n    want: ${w}`); }
}
const block = (rows: any[]): LogBlock => ({ headers: [], rows });

let bn = 1;
function bk(o: { id?: string; date: string; prop: string; net: number; pend?: number; comm?: number; type?: string; ch?: string; repeat?: any; ci?: string }) {
  const c: any[] = new Array(27).fill('');
  c[0] = o.date; c[1] = o.prop; c[2] = 'Guest'; c[3] = o.type || 'Stay'; c[4] = o.ch || 'Airbnb';
  c[9] = o.net; c[10] = o.comm === undefined ? '' : o.comm;
  c[11] = o.pend === undefined ? '' : o.pend;
  c[18] = o.id === undefined ? 'B' + bn : o.id;
  c[20] = o.ci || ''; c[25] = o.repeat === undefined ? '' : o.repeat;
  return { r: bn++, cells: c };
}
let en = 1;
function ex(o: { txn: string; month: string; item: string; prop: string; amt: number; type: string; cat?: string; init?: any }) {
  const c: any[] = new Array(13).fill('');
  c[0] = o.txn; c[1] = o.month; c[2] = o.item; c[3] = o.prop; c[4] = o.cat || 'Rent';
  c[6] = o.amt; c[7] = o.type; c[12] = o.init === undefined ? 0 : o.init;
  return { r: en++, cells: c };
}

/* ══ Shared fixture — identical to qa/math-cash.test.ts ═══════════════════
   Bookings:  B1 2026-05-10 Spira 3028 ₹10,000 · B2 2026-05-20 Spira 2212
              ₹6,000 (₹2,000 pending) · B3 2026-08-05 Spira 3028 ₹4,000
   Expenses:  E1 May Recurring ₹45,000 init_invest=1  (prod expenses id 99)
              E2 May Recurring ₹5,000
              E3 Aug Operating ₹1,000
              E4 May One-time  ₹9,000                                        */
function fixture() {
  bn = 1; en = 1;
  const B = block([
    bk({ date: '2026-05-10', prop: 'Spira 3028', net: 10000 }),
    bk({ date: '2026-05-20', prop: 'Spira 2212', net: 6000, pend: 2000 }),
    bk({ date: '2026-08-05', prop: 'Spira 3028', net: 4000 }),
  ]);
  const E = block([
    ex({ txn: '2026-05-01', month: '2026-05-01', item: 'Monthly rent', prop: 'Spira 3028', amt: 45000, type: 'Recurring', init: 1 }),
    ex({ txn: '2026-05-03', month: '2026-05-01', item: 'Electricity',  prop: 'Spira 3028', amt: 5000,  type: 'Recurring', init: 0 }),
    ex({ txn: '2026-08-06', month: '2026-08-01', item: 'Cleaning',     prop: 'Spira 2212', amt: 1000,  type: 'Operating', init: 0 }),
    ex({ txn: '2026-05-05', month: '2026-05-01', item: 'Sofa',         prop: 'Spira 3028', amt: 9000,  type: 'One-time',  init: 0 }),
  ]);
  return { B, E };
}

/* ── 1. FINDING: computeMonthDrill ignores init_invest; computeCash honours it ─
   computeCash line 409 takes Recurring/Operating rows only when
   `!ciInitInvest(c[12])`. computeMonthDrill line 479 checks the type and
   nothing else. The two run on the SAME Dashboard screen, so May 2026 shows:
     Monthly P&L table / its Expense drill : ₹50,000   (45,000 + 5,000)
     Bank drill "Cash generated by month"  : ₹ 5,000
   ...for the same month, the same property filter, the same rows.
   Hand derivation for May 2026:
     drill rec = 45,000 (E1, init_invest=1) + 5,000 (E2) = 50,000; op = 0
     drill exp = 50,000 · drill net = 16,000 − 50,000 = −34,000
     cash opex =  5,000 · cash cash = 14,000 − 5,000  =   9,000
   Production magnitude: exactly two rows carry Recurring + init_invest=1 —
   id 99 (May 2026, ₹45,000) and id 147 (Aug 2026, ₹51,920) — so the two tables
   disagree by ₹45,000 on the May row, ₹51,920 on the August row and ₹96,920 in
   total (P&L Expense ₹337,839 vs Bank Opex ₹240,919).
   ExpenseForm.tsx:150 labels the flag "Setup capital — excluded from bank
   balance", so computeCash is the intended basis and the drill is the wrong
   number. Minimal fix: add `&& !ciInitInvest(c[12])` at logic.ts:479 (and the
   matching filter in worker index.js:345, which feeds the P&L table itself). */
{
  const { B, E } = fixture();
  const may = computeMonthDrill(B, E, 'All', 'May 2026');
  const cash = computeCash(B, E, 'All', null);
  const mayCash = cash.monthly.find((m) => m.month === 'May 2026')!;

  eq('drill May revenue', may.rev, 16000);
  eq('drill May bookings', may.bk, 2);
    eq('drill May operating', may.op, 0);
    eq('cash-basis May opex', mayCash.opex, 5000);
  eq(' drill May expense must use the same basis as the bank/opex figure',
     may.exp, mayCash.opex);
  eq(' drill May net must reconcile with the cash-basis month',
     may.net, may.rev - mayCash.opex);   // 16,000 − 5,000 = 11,000, not −34,000
}

/* ── 1b. The same divergence across all months (the P&L "Total" row) ──────
   drill('*'): rec = 45,000 + 5,000 = 50,000 · op = 1,000 → exp = 51,000
   computeCash totalExp = 5,000 + 1,000 = 6,000. Gap = 45,000, i.e. exactly the
   init_invest rows the P&L never excluded.                                   */
{
  const { B, E } = fixture();
  const all = computeMonthDrill(B, E, 'All', '*');
  const cash = computeCash(B, E, 'All', null);
  eq('drill all-months revenue', all.rev, 20000);
    eq('cash-basis total expense', cash.totalExp, 6000);
  eq(' all-months drill expense must match the bank basis', all.exp, cash.totalExp);
  eq('no divergence remains between the two bases', all.exp - cash.totalExp, 0);
}

/* ── 1c. August diverges too, and by the second production row's shape ────
   E3 (Operating, init_invest=0) is in both bases, so August only diverges once
   an init_invest row exists in it — production id 147, ₹51,920. Reproduced: */
{
  bn = 1; en = 1;
  const B = block([bk({ date: '2026-08-05', prop: 'Spira 2212', net: 4000 })]);
  const E = block([
    ex({ txn: '2026-08-06', month: '2026-08-01', item: 'August Rent', prop: 'Spira 2212', amt: 51920, type: 'Recurring', init: 1 }),
  ]);
  const aug = computeMonthDrill(B, E, 'All', 'Aug 2026');
  const augCash = computeCash(B, E, 'All', null);
    eq('Aug cash-basis opex', augCash.totalExp, 0);
  eq(' Aug drill expense must match the bank basis', aug.exp, augCash.totalExp);
}

/* ── 2. The month keys themselves agree (no split buckets) ────────────────
   Bookings bucket on ciMonthLabel(c[0]); expenses on ciMonthOf(c[1]). Both
   spell 'May 2026', so a month is ONE row, not two. Proven, not assumed.     */
{
  const { B, E } = fixture();
  const c = computeCash(B, E, 'All', null);
  eq('one row per month, revenue and opex together', c.monthly.map((m) => m.month), ['May 2026', 'Aug 2026']);
  eq('May row carries both sides', c.monthly[0], { month: 'May 2026', recv: 14000, opex: 5000, oneTime: 9000, cash: 0 });
}

/* ── 3. INFO: "Revenue" (drill) and "Received" (bank drill) are different ──
   drill.rev = Σ net = 16,000 for May; cash recv = Σ(net − pending) = 14,000.
   Two different questions with two different labels, so this is by design —
   recorded here so a future change cannot conflate them silently.            */
{
  const { B, E } = fixture();
  eq('drill revenue is gross of pending', computeMonthDrill(B, E, 'All', 'May 2026').rev, 16000);
  eq('cash received is net of pending', computeCash(B, E, 'All', null).monthly[0].recv, 14000);
}

/* ── 4. LATENT: an empty filter string means "All" to computeCash and
        "a property called ''" to computeMonthDrill ──────────────────────────
   computeCash line 389:      `if (filter && filter !== 'All' && ...)`
   computeMonthDrill line 458: `if (filter !== 'All' && ...)`
   With filter === '' the cash card shows the whole business (₹20,000) while
   every P&L drill shows zero. store.tsx seeds the filter to 'All' and the
   picker offers only 'All' + property names, so nothing reaches '' today.    */
{
  const { B, E } = fixture();
  eq('empty filter — computeCash treats it as All', computeCash(B, E, '', null).totalNet, 20000);
  eq('empty filter — drill also treats it as All', computeMonthDrill(B, E, '', '*').rev, 20000);
  eq(' the two must agree on what an empty filter means',
     computeMonthDrill(B, E, '', '*').rev, computeCash(B, E, '', null).totalNet);
}

/* ── 5. computePayouts total must equal computeCash pending ───────────────
   Both are the "awaiting payout" number and both count only pending > 0.
   Fixture: only B2, ₹2,000.                                                  */
{
  const { B, E } = fixture();
  const p = computePayouts(B, 'All');
  eq('payouts total', p.total, 2000);
  eq('payouts list length', p.list.length, 1);
  eq('payouts total equals cash pending', p.total, computeCash(B, E, 'All', null).pending);
}

/* ── 6. computeRepeatByMonth ──────────────────────────────────────────────
   ciRepeat accepts 1 / yes / true / y / repeat (trimmed, lower-cased).
   May 2026: 3 bookings, 2 flagged ('1', 'Yes') → rep 2 / tot 3
   Aug 2026: 1 booking,  0 flagged ('0')        → rep 0 / tot 1
   Months come back in ciMonthSort order: May (202605) before Aug (202608).   */
{
  bn = 1;
  const B = block([
    bk({ date: '2026-08-05', prop: 'Spira 3028', net: 1, repeat: '0' }),
    bk({ date: '2026-05-10', prop: 'Spira 3028', net: 1, repeat: '1' }),
    bk({ date: '2026-05-11', prop: 'Spira 3028', net: 1, repeat: 'Yes' }),
    bk({ date: '2026-05-12', prop: 'Spira 3028', net: 1, repeat: '' }),
  ]);
  eq('repeat by month', computeRepeatByMonth(B, 'All'), [
    { month: 'May 2026', rep: 2, tot: 3 },
    { month: 'Aug 2026', rep: 0, tot: 1 },
  ]);
}

/* ── 7. computeCalendar day roll-up ───────────────────────────────────────
   Money anchors on the booking date (col A), arrivals on the check-in date
   (col U). One booking dated 2026-05-10 with a 2026-05-20 check-in,
   net ₹10,000 · commission ₹500 · pending ₹2,000:
     days['2026-05-10'] = net 10,000 · comm 500 · pending 2,000 · 1 booking · 0 check-ins
     days['2026-05-20'] = net 0 (a check-in carries no money) · 1 check-in
   minMonth '2026-05' · maxMonth '2026-05'.
   A booking whose check-in is its own booking date must still count its net
   ONCE — verified below so the two anchors can never double-book a day.      */
{
  bn = 1;
  const B = block([bk({ date: '2026-05-10', prop: 'Spira 3028', net: 10000, comm: 500, pend: 2000, ci: '2026-05-20' })]);
  const cal = computeCalendar(B, 'All');
  eq('calendar money day', { net: cal.days['2026-05-10'].net, comm: cal.days['2026-05-10'].comm, pending: cal.days['2026-05-10'].pending }, { net: 10000, comm: 500, pending: 2000 });
  eq('calendar money day has the booking', cal.days['2026-05-10'].bookings.length, 1);
  eq('calendar money day has no arrival', cal.days['2026-05-10'].checkins.length, 0);
  eq('calendar arrival day carries no money', cal.days['2026-05-20'].net, 0);
  eq('calendar arrival day has the arrival', cal.days['2026-05-20'].checkins.length, 1);
  eq('calendar month span', [cal.minMonth, cal.maxMonth], ['2026-05', '2026-05']);

  bn = 1;
  const same = computeCalendar(block([bk({ date: '2026-05-10', prop: 'Spira 3028', net: 10000, ci: '2026-05-10' })]), 'All');
  eq('same-day booking + arrival counts net once', same.days['2026-05-10'].net, 10000);
  eq('same-day booking + arrival lists both', [same.days['2026-05-10'].bookings.length, same.days['2026-05-10'].checkins.length], [1, 1]);
}

