/**
 * Turns the live Google Sheet snapshots into a seed .sql file for D1.
 *
 * Inputs (fetched from the still-running Apps Script API — see README):
 *   logs.json   ?action=logs      -> bookings / expenses / savings
 *   props.json  ?action=properties
 *   inv.json    ?action=invData   -> items / movements / lists
 *
 * Run:  node scripts/build-seed.mjs > migrations/0002_seed.sql
 *
 * Deliberately emits plain INSERT statements rather than streaming rows through
 * the API: the dataset is small (~450 rows) and a reviewable .sql file makes the
 * import auditable and repeatable.
 */
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const read = (f) => JSON.parse(readFileSync(join(here, f), 'utf8'));

const logs  = read('logs.json');
const props = read('props.json');
const inv   = read('inv.json');

/* ── SQL literal helpers ── */
const q = (v) => {
  if (v === null || v === undefined || v === '') return "''";
  return "'" + String(v).replace(/'/g, "''") + "'";
};
/* Optional numeric: preserves blank-vs-zero, matching the schema's nullable REALs. */
const n = (v) => (v === '' || v === null || v === undefined) ? 'NULL' : Number(String(v).replace(/[^0-9.\-]/g, '')) || 0;
/* Required numeric: blank collapses to 0. */
const n0 = (v) => (v === '' || v === null || v === undefined) ? 0 : (Number(String(v).replace(/[^0-9.\-]/g, '')) || 0);
const flag = (v) => (v === 1 || v === '1' || v === true) ? 1 : 0;
/* Nullable flag: the sheet left these blank rather than writing 0, and the log
   views render the raw cell, so blank must survive as NULL rather than become 0. */
const nflag = (v) => (v === '' || v === null || v === undefined) ? 'NULL' : flag(v);

const out = [];
const say = (s) => out.push(s);

say('-- Seed data imported from the Google Sheets, generated by scripts/build-seed.mjs.');
say('-- Regenerate rather than hand-edit.');
say('PRAGMA defer_foreign_keys = true;');
say('');

/* ── properties ── */
say('DELETE FROM properties;');
props.forEach((p, i) => {
  say(`INSERT INTO properties (id, name, location, type, status, onboarded, rent, notes, sort) VALUES (` +
      `${q(p.id)}, ${q(p.name)}, ${q(p.location)}, ${q(p.type)}, ${q(p.status)}, ` +
      `${q(p.onboarded)}, ${n(p.rent)}, ${q(p.notes)}, ${i + 1});`);
});
say('');

/* ── bookings (Bookings!A..Z, in sheet column order) ── */
say('DELETE FROM bookings;');
const BCOLS = ['booking_date','property','lead_guest','booking_type','channel','referrer','list_price',
  'discount','guest_paid','net_earned','commission_paid','pending_amount','notes','phone','lead_birth_yr',
  'co_guest','co_guest_birth_yr','guests','booking_id','month','checkin_date','checkout_date',
  'checkin_time','checkout_time','stay_unit','repeat_flag'];
for (const { cells: c } of logs.bookings.rows) {
  const v = [
    q(c[0]), q(c[1]), q(c[2]), q(c[3]), q(c[4]), q(c[5]),
    n(c[6]), n(c[7]), n(c[8]), n0(c[9]), n(c[10]), n(c[11]),
    q(c[12]), q(c[13]), q(c[14]), q(c[15]), q(c[16]), n(c[17]),
    q(c[18]), q(c[19]), q(c[20]), q(c[21]), q(c[22]), q(c[23]), q(c[24]), nflag(c[25])
  ];
  say(`INSERT INTO bookings (${BCOLS.join(', ')}) VALUES (${v.join(', ')});`);
}
say('');

/* ── expenses (Expenses!A..M) ── */
say('DELETE FROM expenses;');
const ECOLS = ['txn_date','expense_month','item','property','category','quantity','amount','type',
  'status','refundable','vendor','notes','init_invest'];
for (const { cells: c } of logs.expenses.rows) {
  const v = [
    q(c[0]), q(c[1]), q(c[2]), q(c[3]), q(c[4]), n(c[5]), n(c[6]),
    q(c[7]), q(c[8]), q(c[9] || 'No'), q(c[10]), q(c[11]), nflag(c[12])
  ];
  say(`INSERT INTO expenses (${ECOLS.join(', ')}) VALUES (${v.join(', ')});`);
}
say('');

/* ── savings ── */
say('DELETE FROM savings;');
for (const { cells: c } of logs.savings.rows) {
  say(`INSERT INTO savings (date, amount, scheme, platform, status, returns, notes, created_at) VALUES (` +
      `${q(c[0])}, ${n0(c[1])}, ${q(c[2])}, ${q(c[3])}, ${q(c[4])}, ${n(c[5])}, ${q(c[6])}, ${q(c[7])});`);
}
say('');

/* ── inventory items ──
   in_stock / pending / low / key are NOT imported: they were spreadsheet
   formulas and are now derived at read time in invData(). */
say('DELETE FROM inv_items;');
for (const it of inv.items || []) {
  say(`INSERT INTO inv_items (item_id, property, category, item, type, required_qty, reorder_level, unit_price, vendor, remarks) VALUES (` +
      `${q(it.id)}, ${q(it.property)}, ${q(it.category)}, ${q(it.item)}, ${q(it.type)}, ` +
      `${n(it.required)}, ${n(it.reorder)}, ${n(it.unitPrice)}, ${q(it.vendor)}, ${q(it.remarks)});`);
}
say('');

say('DELETE FROM inv_movements;');
for (const m of inv.movements || []) {
  say(`INSERT INTO inv_movements (date, item_key, movement, qty, unit_cost, vendor, logged_by, remarks) VALUES (` +
      `${q(m.date)}, ${q(m.key)}, ${q(m.movement)}, ${n0(m.qty)}, ${n(m.unitCost)}, ` +
      `${q(m.vendor)}, ${q(m.by)}, ${q(m.remarks)});`);
}
say('');

/* ── dropdown lists (was the IMS 'Lists' tab) ── */
say('DELETE FROM inv_lists;');
for (const kind of ['properties', 'categories', 'types', 'movements', 'vendors']) {
  (inv.lists?.[kind] || []).forEach((value, i) => {
    say(`INSERT INTO inv_lists (kind, value, sort) VALUES (${q(kind)}, ${q(value)}, ${i + 1});`);
  });
}

process.stdout.write(out.join('\n') + '\n');
